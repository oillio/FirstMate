#!/usr/bin/env python3
"""Repository checks for First Mate. Standard library only.

Checks:
  1. Requirement IDs: each ID is defined once. Each referenced ID is defined.
  2. ADRs: file name, title, and status lines are correct. ADR references exist.
     The generated ADR index is current. Proposed ADRs link an issue (when enabled).
     Use --write-adr-index to rebuild the index.
  3. Advisory-phase guard: no command PGN numbers in code (ADR-0002).
     This is a text tripwire. It is not proof. A stronger guard comes with ADR-0005.

Exit code 0 when all checks pass, 1 when a check fails.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

# An ID is uppercase words joined by hyphens, then a number. Examples:
# CORE-DP-01, AC-CORE-1, FR-CHART-12, OQ-PRN-3, Q-08, SD-04, DEC-001.
ID = r"[A-Z]+(?:-[A-Z]+)*-\d+"
DEFINE_BULLET = re.compile(rf"^\s*-\s+\**({ID})\.\**\s")
DEFINE_HEADING = re.compile(rf"^#+\s+({ID}):")
REFERENCE = re.compile(rf"(?<![A-Za-z0-9-])({ID})(?![A-Za-z0-9-])")

ADR_FILE = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
ADR_TITLE = re.compile(r"^# ADR-(\d{4}): \S")
ADR_STATUS = re.compile(r"^Status: (Proposed|Accepted|Rejected|Deprecated|Superseded by ADR-\d{4})\b")
ADR_REFERENCE = re.compile(r"\bADR-(\d{4})\b")
ADR_ISSUE = re.compile(r"^Issue: #\d+\s*$")

# ADR-0010 rule 3: each Proposed ADR links its board card with an "Issue: #N" line.
# The template (ADR-0000) is exempt. The board exists since PR #34.
REQUIRE_ADR_ISSUE = True

# ADR-0010 rule 4: the ADR index is generated. Do not edit between these markers.
INDEX_BEGIN = "<!-- adr-index:begin (generated by: make adr-index) -->"
INDEX_END = "<!-- adr-index:end -->"

# PGNs that command other equipment. First Mate must not send them (ADR-0002).
# 126208: NMEA group function (used for commands). 127237: heading/track control.
FORBIDDEN_PGNS = ("126208", "127237")
GUARD_DIRS = ("src",)
GUARD_SUFFIXES = (".py", ".rs", ".go", ".ts", ".js", ".c", ".h", ".cpp", ".toml", ".yaml", ".yml", ".json")


@dataclass
class Report:
    errors: list[str] = field(default_factory=list)

    def error(self, where: str, message: str) -> None:
        self.errors.append(f"{where}: {message}")


def id_prefix(identifier: str) -> str:
    return identifier.rsplit("-", 1)[0]


def check_requirements(root: Path, report: Report) -> None:
    req_dir = root / "docs" / "requirements"
    defined: dict[str, str] = {}
    for path in sorted(req_dir.glob("*.md")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = DEFINE_BULLET.match(line) or DEFINE_HEADING.match(line)
            if not match:
                continue
            identifier = match.group(1)
            where = f"{path.relative_to(root)}:{number}"
            if identifier in defined:
                report.error(where, f"requirement {identifier} is defined again (first at {defined[identifier]})")
            else:
                defined[identifier] = where

    prefixes = {id_prefix(identifier) for identifier in defined}
    for path in markdown_files(root):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for identifier in REFERENCE.findall(line):
                if id_prefix(identifier) in prefixes and identifier not in defined:
                    report.error(f"{path.relative_to(root)}:{number}", f"unknown requirement ID {identifier}")


def check_adrs(root: Path, report: Report) -> None:
    adr_dir = root / "docs" / "decisions"
    numbers: dict[str, Path] = {}
    for path in sorted(adr_dir.glob("*.md")):
        if path.name == "README.md":
            continue
        where = str(path.relative_to(root))
        file_match = ADR_FILE.match(path.name)
        if not file_match:
            report.error(where, "ADR file name must be NNNN-lowercase-title.md")
            continue
        number = file_match.group(1)
        if number in numbers:
            report.error(where, f"ADR number {number} is used again (first in {numbers[number].name})")
        numbers[number] = path
        lines = path.read_text(encoding="utf-8").splitlines()
        title = ADR_TITLE.match(lines[0]) if lines else None
        if not title:
            report.error(where, "first line must be '# ADR-NNNN: Title'")
        elif title.group(1) != number:
            report.error(where, f"title number ADR-{title.group(1)} does not match file number {number}")
        statuses = [line for line in lines if line.startswith("Status:")]
        if len(statuses) != 1:
            report.error(where, f"must have exactly one 'Status:' line, found {len(statuses)}")
        elif number != "0000" and not ADR_STATUS.match(statuses[0]):
            report.error(where, f"status is not valid: '{statuses[0]}'")
        elif REQUIRE_ADR_ISSUE and number != "0000" and statuses[0].startswith("Status: Proposed"):
            if not any(ADR_ISSUE.match(line) for line in lines):
                report.error(where, "a Proposed ADR must have an 'Issue: #N' line (ADR-0010)")

    readme = adr_dir / "README.md"
    if numbers and readme.exists():
        current = extract_index(readme.read_text(encoding="utf-8"))
        if current is None:
            report.error(str(readme.relative_to(root)), "ADR index markers are missing")
        elif current != render_adr_index(root):
            report.error(str(readme.relative_to(root)), "ADR index is out of date. Run: make adr-index")

    for path in markdown_files(root):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for reference in ADR_REFERENCE.findall(line):
                if reference not in numbers:
                    report.error(f"{path.relative_to(root)}:{number}", f"unknown ADR-{reference}")


def adr_field(lines: list[str], name: str) -> str:
    for line in lines:
        if line.startswith(f"{name}:"):
            return line.split(":", 1)[1].strip()
    return ""


def render_adr_index(root: Path) -> str:
    rows = ["| ADR | Title | Status | Door |", "|---|---|---|---|"]
    for path in sorted((root / "docs" / "decisions").glob("*.md")):
        match = ADR_FILE.match(path.name)
        if not match or match.group(1) == "0000":
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        title = lines[0].split(":", 1)[1].strip() if lines and ":" in lines[0] else ""
        door = adr_field(lines, "Door").split(".")[0]
        rows.append(f"| [{match.group(1)}]({path.name}) | {title} | {adr_field(lines, 'Status')} | {door} |")
    return "\n".join(rows)


def extract_index(text: str) -> str | None:
    if INDEX_BEGIN not in text or INDEX_END not in text:
        return None
    return text.split(INDEX_BEGIN, 1)[1].split(INDEX_END, 1)[0].strip()


def write_adr_index(root: Path) -> None:
    readme = root / "docs" / "decisions" / "README.md"
    text = readme.read_text(encoding="utf-8")
    if extract_index(text) is None:
        raise SystemExit(f"{readme}: ADR index markers are missing")
    before = text.split(INDEX_BEGIN, 1)[0]
    after = text.split(INDEX_END, 1)[1]
    readme.write_text(f"{before}{INDEX_BEGIN}\n{render_adr_index(root)}\n{INDEX_END}{after}", encoding="utf-8")


def check_command_guard(root: Path, report: Report) -> None:
    for directory in GUARD_DIRS:
        base = root / directory
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix not in GUARD_SUFFIXES:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            for number, line in enumerate(text.splitlines(), 1):
                for pgn in FORBIDDEN_PGNS:
                    if re.search(rf"(?<!\d){pgn}(?!\d)", line):
                        report.error(
                            f"{path.relative_to(root)}:{number}",
                            f"command PGN {pgn} found in code. First Mate must not send commands (ADR-0002).",
                        )


def markdown_files(root: Path) -> list[Path]:
    skip = {".git", "node_modules", "data"}
    return sorted(
        path for path in root.rglob("*.md") if not any(part in skip for part in path.relative_to(root).parts)
    )


def run(root: Path) -> Report:
    report = Report()
    check_requirements(root, report)
    check_adrs(root, report)
    check_command_guard(root, report)
    return report


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    if "--write-adr-index" in sys.argv[1:]:
        write_adr_index(root)
        print("ADR index written: docs/decisions/README.md")
    report = run(root)
    for line in report.errors:
        print(f"ERROR {line}")
    if report.errors:
        print(f"FAIL: {len(report.errors)} error(s)")
        return 1
    print("PASS: requirement IDs, ADRs, command guard")
    return 0


if __name__ == "__main__":
    sys.exit(main())
